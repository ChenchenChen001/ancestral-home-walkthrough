import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output='.';
const {CollisionWorld}=await import(new URL(`../${output}/collision.js`,import.meta.url));
const tri=(a,b,c)=>[...a,...b,...c];
const quad=(a,b,c,d)=>[...tri(a,b,c),...tri(a,c,d)];
const plane=quad([-100,0,-100],[100,0,-100],[100,0,100],[-100,0,100]);
const wall=quad([3,0,-5],[3,4,-5],[3,4,5],[3,0,5]);
const w=new CollisionWorld(new Float32Array([...plane,...wall]));
assert.ok(Math.abs(w.ground(0,0,10).point[1])<1e-5,'floor raycast');
assert.deepEqual(w.step([0,1.7,0],1,0,1,1.7),[1,1.7,0],'clear horizontal movement');
assert.ok(w.step([2.7,1.7,0],.2,0,1,1.7)[0]<2.8,'wall blocks body');
assert.equal(w.step([99,1.7,0],3,0,1,1.7)[0],99,'no falling off mesh');
const stepWorld=new CollisionWorld(new Float32Array([...plane,...quad([1,.2,-5],[5,.2,-5],[5,.2,5],[1,.2,5])]));
assert.ok(Math.abs(stepWorld.step([.8,1.7,0],.4,0,1,1.7)[1]-1.9)<1e-4,'small step raises eye height');
const bodyFile=fs.readFileSync(path.join(root,output,'assets/collision.bin'));
const real=new CollisionWorld(new Float32Array(bodyFile.buffer,bodyFile.byteOffset,bodyFile.byteLength/4));
const ground=real.ground(-150,200,45,1000);assert.ok(ground,'entry ground');
assert.ok(!real.blocked(-150,200,ground.point[1],.05,1.7),'entry standing clearance');
const start=[-150,ground.point[1]+34,200],next=real.step(start,1,0,.05,1.7);
assert.ok(next[0]>start[0]+.9,'actual scene walking movement');
const base=path.join(root,output,'assets/splats');
const index=JSON.parse(fs.readFileSync(path.join(base,'lod-meta.json')));
let refs=0,points=0;
for(const name of index.filenames)assert.ok(!name.startsWith('/')&&!name.includes('..')&&!name.includes(':'),'All scene URLs must remain relative to the Pages project directory');
const metas=index.filenames.map(name=>{let resolved=path.join(base,name);if(name.startsWith('/external-splats/')){const relative=name.slice('/external-splats/'.length);resolved=['walkthrough-assets','walkthrough-assets-2'].map(group=>path.join(root,'..',group,'dist/splats',relative)).find(file=>fs.existsSync(file));assert.ok(resolved,`External resource missing: ${name}`);}const m=JSON.parse(fs.readFileSync(resolved));assert.equal(m.version,2);for(const key of ['means','scales','quats','sh0'])for(const file of m[key].files)assert.ok(fs.existsSync(path.join(path.dirname(resolved),file)));return m;});
function walk(n){for(const [level,lod]of Object.entries(n.lods||{})){assert.ok(lod.file>=0&&lod.file<metas.length);assert.ok(lod.offset+lod.count<=metas[lod.file].count);if(level==='0')points+=lod.count;refs++;}for(const c of n.children||[])walk(c);}
walk(index.tree);assert.equal(points,25077467);
console.log(JSON.stringify({status:'PASS',output,collisionChecks:8,sceneTriangles:real.triangleCount,metadataFiles:metas.length,validatedLodReferences:refs,sourceSplats:points},null,2));
